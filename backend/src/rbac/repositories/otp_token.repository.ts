import { IDatabase, ITask } from 'pg-promise';
import { OtpTokens } from '../models/otp_tokens.model';
import { CreateOtpTokenInput } from '../types/repository.types';
import { TransactionTask } from '../utils/transaction.utils';

export interface IOtpTokenRepository {
  create(input: CreateOtpTokenInput, t: TransactionTask): Promise<OtpTokens>;
  findLatestByUser(userId: string, t: TransactionTask): Promise<OtpTokens | null>;
  incrementAttempts(userId: string, t: TransactionTask): Promise<number>;
  deleteExpired(t: TransactionTask): Promise<void>;
  deleteOnSuccess(userId: string, otpHash: string, t: TransactionTask): Promise<boolean>;
  countRecentOtps(userId: string, minutesWindow: number, t: TransactionTask): Promise<number>;
}

export class OtpTokenRepository implements IOtpTokenRepository {
  private tableName = 'otp_tokens';

  constructor(private db: IDatabase<unknown>) { }

  protected async query<T>(t: TransactionTask, text: string, params?: unknown[]): Promise<T[]> {
    return t.any<T>(text, params);
  }

  /** Count OTPs generated by a user in the last X minutes */
  async countRecentOtps(userId: string, minutesWindow: number, t: TransactionTask): Promise<number> {
    const res = await t.one<{ count: number }>(
      `SELECT COUNT(*)::int AS count 
     FROM ${this.tableName}
     WHERE user_id = $1 
       AND created_at > NOW() - INTERVAL '${minutesWindow} minutes'`,
      [userId]
    );
    return res.count;
  }


  /** Create a new OTP token entry */
  async create(input: CreateOtpTokenInput, t: TransactionTask): Promise<OtpTokens> {
    const res = await t.one<OtpTokens>(
      `INSERT INTO ${this.tableName} 
       (user_id, otp_hash, expires_at, sent_to, ip_address, user_agent, attempt_count)
       VALUES ($1, $2, $3, $4, $5, $6, COALESCE($7, 0))
       RETURNING *`,
      [
        input.user_id,
        input.otp_hash,
        input.expires_at,
        input.sent_to,
        input.ip_address,
        input.user_agent,
        input.attempt_count ?? null
      ]
    );

    return res;
  }


  /** Get the latest valid OTP token for a user */
  async findLatestByUser(userId: string, t: TransactionTask): Promise<OtpTokens | null> {
    const res = await this.query<OtpTokens>(
      t,
      `SELECT * FROM ${this.tableName}
       WHERE user_id = $1 AND expires_at > NOW()
       ORDER BY created_at DESC
       LIMIT 1`,
      [userId]
    );
    return res[0] ?? null;
  }

  /** Increment attempts counter for the latest valid OTP token */
  async incrementAttempts(userId: string, t: TransactionTask): Promise<number> {
    const res = await t.oneOrNone<{ attempt_count: number }>(
      `UPDATE ${this.tableName}
       SET attempt_count = attempt_count + 1
       WHERE id = (
         SELECT id FROM ${this.tableName}
         WHERE user_id = $1 AND expires_at > NOW()
         ORDER BY created_at DESC
         LIMIT 1
       )
       RETURNING attempt_count`,
      [userId]
    );
    return res?.attempt_count ?? 0;
  }

  /** Delete all expired OTP tokens (on-demand cleanup) */
  async deleteExpired(t: TransactionTask): Promise<void> {
    await t.none(`DELETE FROM ${this.tableName} WHERE expires_at <= NOW()`);
  }

  /** Atomically validate OTP and delete if correct */
  async deleteOnSuccess(userId: string, otpHash: string, t: TransactionTask): Promise<boolean> {
    const res = await t.result(
      `DELETE FROM ${this.tableName}
     WHERE id = (SELECT id FROM ${this.tableName} 
     WHERE user_id = $1
         AND otp_hash = $2
         AND expires_at > NOW())`,
      [userId, otpHash]
    );
    return res.rowCount > 0; // true = OTP existed and deleted
  }
}
